import { useEffect, useRef, useState } from "react";

// Attaches an IntersectionObserver to the returned ref; `visible` flips true the first time the
// element scrolls into view and stays true (a one-shot reveal, not a flicker on every scroll).
export default function useReveal(threshold = 0.15) {
  const ref = useRef(null);
  const [visible, setVisible] = useState(false);

  useEffect(() => {
    const el = ref.current;
    if (!el) return;
    const obs = new IntersectionObserver(
      (entries) => {
        if (entries[0].isIntersecting) {
          setVisible(true);
          obs.disconnect();
        }
      },
      { threshold }
    );
    obs.observe(el);
    return () => obs.disconnect();
  }, [threshold]);

  return [ref, visible];
}
